    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String nome = txtNome.getText().trim();
        String descricao = txtDescricao.getText().trim();

        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o nome da categoria."
            );
            return;
        }

        Categoria categoria = new Categoria(0, nome, descricao);
        CategoriaDAO dao = new CategoriaDAO();

        try {
            if (dao.inserir(categoria)) {
                JOptionPane.showMessageDialog(this, "Categoria cadastrada com sucesso!"
                );

                carregarCategorias();
                limparCampos();
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,"Erro ao cadastrar categoria: " + e.getMessage()
            );
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed

        String idTexto = txtId.getText().trim();
        String nome = txtNome.getText().trim();
        String descricao = txtDescricao.getText().trim();

        if (idTexto.isEmpty() || nome.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Selecione uma categoria e informe o nome.");
            return;
        }

        try {
            int id = Integer.parseInt(idTexto);

            Categoria categoria =new Categoria(id, nome, descricao);

            CategoriaDAO dao = new CategoriaDAO();

            if (dao.atualizar(categoria)) {JOptionPane.showMessageDialog(this,"Categoria atualizada com sucesso!");
                carregarCategorias();
                limparCampos();
            } else {JOptionPane.showMessageDialog(this,"Nenhuma categoria foi atualizada.");
            }

        } catch (NumberFormatException e) {JOptionPane.showMessageDialog(this, "ID inválido.");
        } catch (SQLException e) {JOptionPane.showMessageDialog(this,"Erro ao atualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnLimparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimparActionPerformed

    limparCampos();
    tblItens.clearSelection();
    }//GEN-LAST:event_btnLimparActionPerformed

    private void btnRemoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverActionPerformed

        String idTexto = txtId.getText().trim();

        if (idTexto.isEmpty()) {JOptionPane.showMessageDialog(this,"Selecione uma categoria para remover.");
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(this,"Deseja realmente remover esta categoria?","Confirmar exclusão",JOptionPane.YES_NO_OPTION
        );

        if (resposta != JOptionPane.YES_OPTION) {return;
        }

        try {int id = Integer.parseInt(idTexto);

            CategoriaDAO dao = new CategoriaDAO();

            if (dao.excluir(id)) {
                JOptionPane.showMessageDialog(this,"Categoria removida com sucesso!");
                carregarCategorias();
                limparCampos();
            } else {
                JOptionPane.showMessageDialog(this,"Nenhuma categoria foi removida.");
            }

        } catch (NumberFormatException e) {JOptionPane.showMessageDialog(this, "ID inválido.");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,"Erro ao remover: " + e.getMessage());
        }
    }//GEN-LAST:event_btnRemoverActionPerformed


    private void limparCampos() {
        txtId.setText("");
        txtNome.setText("");
        txtDescricao.setText("");
    }


    private void carregarCategorias() {
        CategoriaDAO dao = new CategoriaDAO();

        try {
            List<Categoria> categorias = dao.listar();

            DefaultTableModel modelo =
                    (DefaultTableModel) tblItens.getModel();

            modelo.setRowCount(0);

            for (Categoria categoria : categorias) {
                modelo.addRow(new Object[]{
                    categoria.getId(),
                    categoria.getNome(),
                    categoria.getDescricao()
                });
            }

        } catch (SQLException e) {JOptionPane.showMessageDialog(this, "Erro ao carregar categorias: " + e.getMessage()
            );
        }
    }

    
