    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        
    String nome = txtNome.getText().trim();
    String cpf = txtCpf.getText().trim();
    String telefone = txtTelefone.getText().trim();
    String email = txtEmail.getText().trim();
    String cep = txtCep.getText().trim();

    if (nome.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Informe o nome do cliente.");
        return;
    }

    Cliente cliente = new Cliente(
            0, nome, cpf, telefone, email, cep);

    try {
        ClienteDAO dao = new ClienteDAO();

        if (dao.inserir(cliente)) {
            JOptionPane.showMessageDialog(this,
                    "Cliente cadastrado com sucesso!");
            carregarClientes();
            limparCampos();
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao cadastrar cliente: " + e.getMessage());
    }

    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        
    String idTexto = txtId.getText().trim();
    String nome = txtNome.getText().trim();

    if (idTexto.isEmpty() || nome.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Selecione um cliente e informe o nome.");
        return;
    }

    try {
        int id = Integer.parseInt(idTexto);

        Cliente cliente = new Cliente(
                id,
                nome,
                txtCpf.getText().trim(),
                txtTelefone.getText().trim(),
                txtEmail.getText().trim(),
                txtCep.getText().trim()
        );

        ClienteDAO dao = new ClienteDAO();

        if (dao.atualizar(cliente)) {
            JOptionPane.showMessageDialog(this,
                    "Cliente atualizado com sucesso!");
            carregarClientes();
            limparCampos();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Cliente não encontrado.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "ID inválido.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao atualizar: " + e.getMessage());
    }

    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnLimparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimparActionPerformed
        
    limparCampos();
    tblItens.clearSelection();

    }//GEN-LAST:event_btnLimparActionPerformed

    private void btnRemoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverActionPerformed
        
    String idTexto = txtId.getText().trim();

    if (idTexto.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Selecione um cliente para remover.");
        return;
    }

    int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente remover este cliente?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION
    );

    if (resposta != JOptionPane.YES_OPTION) {
        return;
    }

    try {
        int id = Integer.parseInt(idTexto);
        ClienteDAO dao = new ClienteDAO();

        if (dao.excluir(id)) {
            JOptionPane.showMessageDialog(this,
                    "Cliente removido com sucesso!");
            carregarClientes();
            limparCampos();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Cliente não encontrado.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "ID inválido.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao remover: " + e.getMessage());
    }

    }//GEN-LAST:event_btnRemoverActionPerformed

    
    private void carregarClientes() {
        try {
            ClienteDAO dao = new ClienteDAO();
            List<Cliente> clientes = dao.listar();

            DefaultTableModel modelo =
                    (DefaultTableModel) tblItens.getModel();

            modelo.setRowCount(0);

            for (Cliente cliente : clientes) {
                modelo.addRow(new Object[]{
                    cliente.getId(),
                    cliente.getNome(),
                    cliente.getCpf(),
                    cliente.getTelefone(),
                    cliente.getEmail(),
                    cliente.getCep()
                });
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao carregar clientes: " + e.getMessage());
        }
    }

    private void limparCampos() {
        txtId.setText("");
        txtNome.setText("");
        txtCpf.setText("");
        txtTelefone.setText("");
        txtEmail.setText("");
        txtCep.setText("");
    }

    
