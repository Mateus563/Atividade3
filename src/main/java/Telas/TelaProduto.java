    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
    String nome = txtNome.getText().trim();
    String descricao = txtDescricao.getText().trim();
    String precoTexto = txtPreco.getText().trim()
            .replace(",", ".");
    String quantidadeTexto = txtQuantEstoque.getText().trim();
    String categoriaTexto = txtCodCategoria.getText().trim();

    if (nome.isEmpty() || precoTexto.isEmpty()
            || quantidadeTexto.isEmpty() || categoriaTexto.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Preencha nome, preço, estoque e código da categoria.");
        return;
    }

    try {
        double preco = Double.parseDouble(precoTexto);
        int quantidade = Integer.parseInt(quantidadeTexto);
        int idCategoria = Integer.parseInt(categoriaTexto);

        if (preco < 0 || quantidade < 0 || idCategoria <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Confira o preço, o estoque e o código da categoria.");
            return;
        }

        Produto produto = new Produto(
                0, nome, descricao, preco, quantidade, idCategoria);

        ProdutoDAO dao = new ProdutoDAO();

        if (dao.inserir(produto)) {
            JOptionPane.showMessageDialog(this,
                    "Produto cadastrado com sucesso!");
            carregarProdutos();
            limparCampos();
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Preço, estoque ou código da categoria inválido.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao cadastrar produto: " + e.getMessage());
    }

    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed

    try {
        if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um produto para atualizar.");
            return;
        }

        String nome = txtNome.getText().trim();

        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Informe o nome do produto.");
            return;
        }

        int id = Integer.parseInt(txtId.getText().trim());
        double preco = Double.parseDouble(
                txtPreco.getText().trim().replace(",", "."));
        int quantidade = Integer.parseInt(
                txtQuantEstoque.getText().trim());
        int idCategoria = Integer.parseInt(
                txtCodCategoria.getText().trim());

        if (preco < 0 || quantidade < 0 || idCategoria <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Confira o preço, o estoque e a categoria.");
            return;
        }

        Produto produto = new Produto(
                id,
                nome,
                txtDescricao.getText().trim(),
                preco,
                quantidade,
                idCategoria
        );

        ProdutoDAO dao = new ProdutoDAO();

        if (dao.atualizar(produto)) {
            JOptionPane.showMessageDialog(this,
                    "Produto atualizado com sucesso!");
            carregarProdutos();
            limparCampos();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Produto não encontrado.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Confira o ID, o preço, o estoque e a categoria.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao atualizar produto: " + e.getMessage());
    }

    }//GEN-LAST:event_btnAtualizarActionPerformed

