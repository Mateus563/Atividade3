    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
    try {
        String data = txtDtVenda.getText().trim();
        String forma = txtFormaPg.getText().trim();

        if (data.isEmpty() || forma.isEmpty()
                || txtVlTotal.getText().trim().isEmpty()
                || txtCodCliente.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Preencha todos os campos da venda.");
            return;
        }

        double valor = Double.parseDouble(
            txtVlTotal.getText().trim().replace(",", ".")
        );
        int idCliente = Integer.parseInt(
            txtCodCliente.getText().trim()
        );

        Venda venda = new Venda(
            0, data, valor, forma, idCliente
        );

        if (new VendaDAO().inserir(venda)) {
            JOptionPane.showMessageDialog(this,
                "Venda cadastrada com sucesso!");
            carregarVendas();
            limparCampos();
        }
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this,
            "Confira os números e a data. Use a data no formato AAAA-MM-DD.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Erro ao cadastrar venda: " + e.getMessage());
    }
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
            try {
        if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Selecione uma venda na tabela.");
            return;
        }

        Venda venda = new Venda(
            Integer.parseInt(txtId.getText().trim()),
            txtDtVenda.getText().trim(),
            Double.parseDouble(
                txtVlTotal.getText().trim().replace(",", ".")
            ),
            txtFormaPg.getText().trim(),
            Integer.parseInt(txtCodCliente.getText().trim())
        );

        if (new VendaDAO().atualizar(venda)) {
            JOptionPane.showMessageDialog(this,
                "Venda atualizada com sucesso!");
            carregarVendas();
            limparCampos();
        } else {
            JOptionPane.showMessageDialog(this,
                "Nenhuma venda foi atualizada.");
        }
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this,
            "Confira os campos numéricos e a data (AAAA-MM-DD).");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Erro ao atualizar venda: " + e.getMessage());
    }
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnLimparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimparActionPerformed
        limparCampos();
    tblItens.clearSelection();
    }//GEN-LAST:event_btnLimparActionPerformed

    private void btnRemoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverActionPerformed
            try {
        if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Selecione uma venda na tabela.");
            return;
        }

        int id = Integer.parseInt(txtId.getText().trim());

        int opcao = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente remover esta venda?",
            "Confirmar remoção",
            JOptionPane.YES_NO_OPTION
        );

        if (opcao == JOptionPane.YES_OPTION) {
            if (new VendaDAO().excluir(id)) {
                JOptionPane.showMessageDialog(this,
                    "Venda removida com sucesso!");
                carregarVendas();
                limparCampos();
            } else {
                JOptionPane.showMessageDialog(this,
                    "Nenhuma venda foi removida.");
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Erro ao remover venda: " + e.getMessage()
            + "\nVerifique se existem itens vinculados a esta venda.");
    }
    }//GEN-LAST:event_btnRemoverActionPerformed

        private void carregarVendas() {
        try {
            VendaDAO dao = new VendaDAO();
            List<Venda> vendas = dao.listar();

            DefaultTableModel modelo =
                (DefaultTableModel) tblItens.getModel();

            modelo.setRowCount(0);

            for (Venda venda : vendas) {
                modelo.addRow(new Object[]{
                    venda.getId(),
                    venda.getDataVenda(),
                    venda.getValorTotal(),
                    venda.getFormaPagamento(),
                    venda.getIdCliente(),
                    ""
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this, "Erro ao carregar vendas: " + e.getMessage()
            );
        }
    }

    private void limparCampos() {
        txtId.setText("");
        txtDtVenda.setText("");
        txtVlTotal.setText("");
        txtFormaPg.setText("");
        txtCodCliente.setText("");
        txtProdQuant.setText("");
    }

